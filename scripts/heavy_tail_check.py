"""Why does the beta-binomial gate still split single-class real reads?  Test the hypothesis that real heterozygous-site VAFs have
heavier tails than the beta distribution the gate assumes.

Uses the HG002-only shared-heterozygous sites (the f = 0 control of giab_mixture_check.py).  Three checks:
  1. Likelihood: one beta-binomial (q, rho) against a two-component scale mixture (same q, rho1 / rho2, weight w), on all sites.
  2. Gate calibration: the v3.2 gate p-value on real 700-site draws at depth 60 against draws simulated from the fitted
     single beta-binomial with the same depths; false-split rate = share of p < ALPHA.
  3. Sufficiency: the same gate on draws simulated from the fitted two-component mixture.
Usage: heavy_tail_check.py [N_DRAWS]
"""
import sys
from pathlib import Path

import numpy as np
from scipy.optimize import minimize
from scipy.special import betaln, expit, gammaln, logit

HERE = Path(__file__).resolve().parent
sys.path.append(str(HERE))
sys.path.append(str(__import__('pathlib').Path(__file__).resolve().parent.parent / 'model'))
from giab_mixture_check import OUTDIR, draw_class, load  # noqa: E402
from hapmap_check import wilson  # noqa: E402

DEPTH, N_SITES, MODEL_RHO, MIN_DEPTH = 60, 700, 0.0025, 8
REPORT = OUTDIR / 'HEAVY_TAIL_CHECK.md'


def bb_logpmf(a, n, q, rho):
    k = 1 / rho - 1
    return gammaln(n + 1) - gammaln(a + 1) - gammaln(n - a + 1) + betaln(a + q * k, n - a + (1 - q) * k) - betaln(q * k, (1 - q) * k)


def nll_one(p, a, n):
    return -bb_logpmf(a, n, expit(p[0]), expit(p[1])).sum()


def nll_two(p, a, n):
    q, r1, r2, w = expit(p)
    return -np.logaddexp(np.log1p(-w) + bb_logpmf(a, n, q, r1), np.log(w) + bb_logpmf(a, n, q, r2)).sum()


def fit_models(a, n):
    q0 = a.sum() / n.sum()
    one = minimize(nll_one, [logit(q0), logit(0.003)], args=(a, n), method='Nelder-Mead')
    best = None
    for r2 in (0.02, 0.05, 0.15):                                              # several starts: the mixture likelihood is multimodal
        two = minimize(nll_two, [logit(q0), logit(0.001), logit(r2), logit(0.05)], args=(a, n), method='Nelder-Mead',
                       options={'maxiter': 4000, 'xatol': 1e-4, 'fatol': 1e-4})
        best = two if best is None or two.fun < best.fun else best
    return (expit(one.x[0]), expit(one.x[1]), one.fun), (*expit(best.x), best.fun)


def sim_bb(rng, n, q, rho):
    k = 1 / rho - 1
    return rng.binomial(n, rng.beta(q * k, (1 - q) * k, size=len(n)))


def sim_two(rng, n, q, r1, r2, w):
    rho = np.where(rng.random(len(n)) < w, r2, r1)
    k = 1 / rho - 1
    return rng.binomial(n, rng.beta(q * k, (1 - q) * k))


def gate_rate(ps: np.ndarray, alpha: float) -> str:
    lo, hi = wilson(int((ps < alpha).sum()), len(ps))
    return f'{(ps < alpha).mean():.2f} [{lo:.2f}, {hi:.2f}]'


def main(n_draws: int) -> None:
    import partition_model_v3 as base
    import partition_model_v3_2 as bb
    bb.RHO = MODEL_RHO
    d, m2, m3 = load()
    pool = d[(d.g2 == 1) & (d.g3 == 1)]
    out = ['# Heavy-tail check on HG002 shared-heterozygous sites (auto-generated by scripts/heavy_tail_check.py)', '']

    out += ['## 1. One beta-binomial against a two-component scale mixture (all sites, unthinned and thinned)', '',
            '| depth | sites | q | rho (one) | rho1 / rho2, weight w (two) | log-lik gain | AIC gain |', '|---|---|---|---|---|---|---|']
    rng0 = np.random.default_rng(11)
    for dt in (0, 30, 60):
        if dt == 0:
            a, n = pool.a2.values.astype(float), pool.d2.values.astype(float)
        else:
            p = min(1.0, dt / m2)
            a = rng0.binomial(pool.a2.values, p)
            n = a + rng0.binomial(pool.d2.values - pool.a2.values, p)
            a, n = a.astype(float), n.astype(float)
        keep = n >= MIN_DEPTH
        a, n = a[keep], n[keep]
        (q, rho, f1), (q2, r1, r2, w, f2) = fit_models(a, n)
        out.append(f'| {dt or "full (%.0f)" % n.mean()} | {len(a)} | {q:.3f} | {rho:.4f} | {r1:.4f} / {r2:.3f}, w = {w:.3f} | {f1 - f2:.1f} | {2 * (f1 - f2) - 4:.1f} |')                  # two extra parameters (rho2, w)
        if dt == 0:
            fit_one, fit_two = (q, rho), (q2, r1, r2, w)

    rng = np.random.default_rng(2031)
    real, null1, null2 = [], [], []
    for i in range(n_draws):
        a, n = draw_class(pool, rng, N_SITES, 0.0, DEPTH, m2, m3)
        keep = n >= MIN_DEPTH
        a, n = a[keep], n[keep]
        real.append(bb._gate_p(a, n, i))
        null1.append(bb._gate_p(sim_bb(rng, n, a.sum() / n.sum(), fit_one[1]), n, i))
        null2.append(bb._gate_p(sim_two(rng, n, a.sum() / n.sum(), fit_two[1], fit_two[2], fit_two[3]), n, i))
    out += ['', f'## 2-3. v3.2 gate (rho {MODEL_RHO}) on 700-site draws at depth {DEPTH}: share of gate p-values below ALPHA = {base.ALPHA} ({n_draws} draws each)', '',
            '| data | false-split rate (p < ALPHA) [95% CI] | median gate p |', '|---|---|---|']
    for name, ps in (('real HG002 reads', real), ('simulated: single beta-binomial (fitted rho)', null1),
                     ('simulated: two-component mixture (fitted)', null2)):
        ps = np.asarray(ps)
        out.append(f'| {name} | {gate_rate(ps, base.ALPHA)} | {np.median(ps):.3f} |')
    REPORT.write_text('\n'.join(out) + '\n', encoding='utf-8')
    print('\n'.join(out))


if __name__ == '__main__':
    main(int(sys.argv[1]) if len(sys.argv) > 1 else 100)
