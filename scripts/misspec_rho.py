"""Misspecified-rho sensitivity (experiment 2): how do false splits and detections change when v3.2 is given the wrong rho?

Simulated tumours (power_scale.simulate: 700 SNVs, 50/50 clones, depth {30,100} x purity {.4,.8}, delta {0, .25, .55}) are held
fixed per seed while the rho supplied to the model varies.  Assumed rho 0 runs the binomial model v3 (v3.2 divides by rho), any
other value runs v3.2; one model per process because v3.2 patches v3 on import.  Resumable; appends one JSON line per cell.
Usage: misspec_rho.py run MODEL(v3|v32) TRUE_RHO ASSUMED_COMMA_LIST NSEEDS BUDGET_SECONDS
       misspec_rho.py report                     (writes reports/v3_falsesplit/MISSPEC_RHO.md)
"""
import importlib
import itertools
import json
import sys
import time
from pathlib import Path

sys.path.append(str(Path(__file__).resolve().parent))
sys.path.append(str(__import__('pathlib').Path(__file__).resolve().parent.parent / 'model'))
from power_scale import simulate  # noqa: E402

REPORTS = Path(__file__).resolve().parent.parent / 'reports' / 'v3_falsesplit'
OUT, REPORT = REPORTS / 'misspec_rho.jsonl', REPORTS / 'MISSPEC_RHO.md'
DEPTHS, PURITIES, DELTAS = (30, 100), (0.4, 0.8), (0.0, 0.25, 0.55)


def read_records() -> list[dict]:
    return [json.loads(line) for line in OUT.read_text().splitlines() if line.strip()] if OUT.exists() else []


def run(which: str, true_rho: float, assumed: list[float], n_seeds: int, budget: float) -> None:
    mod = importlib.import_module('partition_model_v3' if which == 'v3' else 'partition_model_v3_2')
    done = {r['key'] for r in read_records()}
    t0 = time.time()
    for rho_assumed, depth, purity, delta in itertools.product(assumed, DEPTHS, PURITIES, DELTAS):
        key = f'true{true_rho}|assumed{rho_assumed}|d{depth}|p{purity}|dl{delta}'
        if key in done:
            continue
        if time.time() - t0 > budget:
            print('budget reached')
            return
        if which == 'v32':
            mod.RHO = rho_assumed
        ks = [mod.fit_predict(*simulate(s, depth, purity, true_rho, delta), purity, seed=s)['k'] for s in range(n_seeds)]
        rec = dict(key=key, model=which, true_rho=true_rho, assumed=rho_assumed, depth=depth, purity=purity, delta=delta,
                   n=n_seeds, hits=sum(k >= 2 for k in ks), ks=ks)
        with OUT.open('a') as f:
            f.write(json.dumps(rec) + '\n')
        print(key, rec['hits'], '/', n_seeds, flush=True)
    print('ALL DONE')


def report() -> None:
    """Pool the four depth x purity cells: false splits (delta 0) and detections (delta .25, .55) per assumed rho."""
    lines = ['# Misspecified rho: v3.2 given the wrong rho (auto-generated by scripts/misspec_rho.py)', '',
             'Pooled over depth {30,100} x purity {.4,.8}; each entry is splits / runs.  Delta 0 is a single clone, so every split '
             'is false; delta .25 and .55 are two-clone tumours, so a split is a detection.  Assumed rho 0 is the binomial model v3.',
             '', '| true rho | assumed rho | false splits (delta 0) | detections, delta .25 | detections, delta .55 |',
             '|---|---|---|---|---|']
    pooled: dict = {}
    for r in read_records():
        hits, n = pooled.get((r['true_rho'], r['assumed'], r['delta']), (0, 0))
        pooled[(r['true_rho'], r['assumed'], r['delta'])] = (hits + r['hits'], n + r['n'])
    for true_rho, assumed in sorted({(t, a) for t, a, _ in pooled}):
        cells = [f'{pooled[(true_rho, assumed, d)][0]} / {pooled[(true_rho, assumed, d)][1]}' if (true_rho, assumed, d) in pooled
                 else '-' for d in DELTAS]
        lines.append(f'| {true_rho:g} | {assumed:g} | ' + ' | '.join(cells) + ' |')
    REPORT.write_text('\n'.join(lines) + '\n', encoding='utf-8')
    print('\n'.join(lines))


if __name__ == '__main__':
    if sys.argv[1] == 'run':
        run(sys.argv[2], float(sys.argv[3]), [float(x) for x in sys.argv[4].split(',')], int(sys.argv[5]), float(sys.argv[6]))
    else:
        report()
