"""Does PyClone-VI's fixed beta-binomial precision absorb an unequal subclone? (direction 4)  Usage: pyclone_precision.py run | report
PyClone-VI's beta-binomial density has a FIXED precision (CLI --precision, default 200, i.e. rho = 1/(1+precision) = .005); it does not
fit dispersion.  A subclone whose extra VAF variance is below that rho is indistinguishable from the density's own noise.  This sweeps
the precision on the unequal-clone simulations (data/sim_uneq: depth 60, purity .6, 20% subclone) and counts splits (K = clusters
holding at least one SNV, K2 = clusters holding at least 2% of SNVs).  Same fit settings as the accuracy reruns (10 clusters, 10 restarts).
run -> reports/v3_falsesplit/pyclone_precision.jsonl (resumable); report -> reports/v3_falsesplit/PYCLONE_PRECISION.md."""
import json
import subprocess
import sys
import tempfile
from collections import defaultdict
from concurrent.futures import ThreadPoolExecutor, as_completed
from pathlib import Path

import pandas as pd

PROJECT = Path(__file__).resolve().parent.parent
CLI = PROJECT / '.venv_pyclone' / 'Scripts' / 'pyclone-vi.exe'
DATA = PROJECT / 'data' / 'sim_uneq'
OUT = PROJECT / 'reports' / 'v3_falsesplit' / 'pyclone_precision.jsonl'
REPORT = PROJECT / 'reports' / 'v3_falsesplit' / 'PYCLONE_PRECISION.md'
PRECISIONS = (50, 200, 1000, 5000)
CELLS = {(0.0, 0.0), (0.0, 0.2), (0.0, 0.3), (0.02, 0.0)}  # (rho, delta): clean false split, the two subclones, noisy false split
SEEDS = 15
WORKERS = 6
MIN_FRACTION = 0.02


def fit_k(table: Path, precision: int) -> tuple[int, int]:
    """(clusters with >= 1 SNV, clusters with >= 2% of SNVs) for one PyClone-VI beta-binomial fit."""
    with tempfile.TemporaryDirectory(dir=PROJECT / 'reports' / 'v3_falsesplit') as tmp:
        h5, res = Path(tmp) / 'fit.h5', Path(tmp) / 'res.tsv'
        subprocess.run([str(CLI), 'fit', '-i', str(table), '-o', str(h5), '-c', '10', '-d', 'beta-binomial', '-r', '10',
                        '--precision', str(precision)], check=True, capture_output=True)
        subprocess.run([str(CLI), 'write-results-file', '-i', str(h5), '-o', str(res)], check=True, capture_output=True)
        sizes = pd.read_csv(res, sep='\t').cluster_id.value_counts()
    return int(len(sizes)), int((sizes / sizes.sum() >= MIN_FRACTION).sum())


def run() -> None:
    manifest = [json.loads(l) for l in (DATA / 'manifest.jsonl').read_text(encoding='utf-8').splitlines() if l.strip()]
    done = {(r['id'], r['precision']) for r in map(json.loads, OUT.read_text(encoding='utf-8').splitlines())} if OUT.exists() else set()
    jobs = [(m, p) for m in manifest if m['seed'] < SEEDS and (m['rho'], m['delta']) in CELLS
            for p in PRECISIONS if (m['id'], p) not in done]
    print(len(jobs), 'fits to run', flush=True)
    with ThreadPoolExecutor(WORKERS) as pool:  # the fits are external processes, so threads suffice
        futures = {pool.submit(fit_k, DATA / 'pyclone' / f"{m['id']}.tsv", p): (m, p) for m, p in jobs}
        for fut in as_completed(futures):
            m, precision = futures[fut]
            k, k2 = fut.result()
            with OUT.open('a', encoding='utf-8', newline='\n') as f:
                f.write(json.dumps(dict(id=m['id'], rho=m['rho'], delta=m['delta'], precision=precision, k=k, k2=k2)) + '\n')
            print(m['id'], precision, k, k2, flush=True)


def report() -> None:
    cells: dict = defaultdict(lambda: [0, 0, 0])
    for r in map(json.loads, OUT.read_text(encoding='utf-8').splitlines()):
        c = cells[(r['rho'], r['delta'], r['precision'])]
        c[0] += 1
        c[1] += r['k'] >= 2
        c[2] += r['k2'] >= 2
    keys = sorted({(rho, delta) for rho, delta, _ in cells})
    lines = ['# PyClone-VI beta-binomial: splits versus the fixed precision (auto-generated by scripts/pyclone_precision.py)', '',
             'Unequal clones (20% of SNVs in the subclone, depth 60, purity .6, 15 seeds).  Each cell: splits (K>=1 SNV per cluster) / '
             'splits (clusters >= 2% of SNVs) / samples.  rho = 1/(1+precision): 50 -> .020, 200 -> .005 (default), 1000 -> .001, 5000 -> .0002.',
             '', '| precision | ' + ' | '.join(f'rho {rho}, delta {delta}' for rho, delta in keys) + ' |', '|---|' + '---|' * len(keys)]
    for p in PRECISIONS:
        cols = [f'{cells[(rho, delta, p)][1]} / {cells[(rho, delta, p)][2]} / {cells[(rho, delta, p)][0]}' if (rho, delta, p) in cells else '-'
                for rho, delta in keys]
        lines.append(f'| {p} | ' + ' | '.join(cols) + ' |')
    REPORT.write_text('\n'.join(lines) + '\n', encoding='utf-8')
    print('\n'.join(lines))


if __name__ == '__main__':
    if len(sys.argv) != 2 or sys.argv[1] not in ('run', 'report'):
        raise SystemExit('usage: pyclone_precision.py run | report')
    run() if sys.argv[1] == 'run' else report()
